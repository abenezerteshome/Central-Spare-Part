// src/components/brands/BrandsForm.tsx
import React, { useEffect } from 'react';
import { useForm } from 'react-hook-form';
import { useMutation } from '../../hooks/useMutation';
import { endpoints } from '../../api/endpoints';
import { useToast } from '../../hooks/useToast';

interface Brand {
  id?: string;
  name: string;
  country?: string;
  notes?: string;
}

interface BrandsFormProps {
  brand?: Brand | null;
  onSuccess?: () => void;
}

const BrandsForm: React.FC<BrandsFormProps> = ({ brand, onSuccess }) => {
  const toast = useToast();
  const { register, handleSubmit, reset } = useForm<Brand>();

  const { mutate: createBrand } = useMutation(endpoints.BRANDS.CREATE, 'post');
  const { mutate: _updateBrand } = useMutation(
    (id: string) => `${endpoints.BRANDS.UPDATE(id)}`,
    'put'
  );

  // wrap the internal mutate so we expose (id, data) -> Promise
  const updateBrand = (id: string, data: Brand) => (_updateBrand as any)(data, id);

  // Pre-fill form when editing
  useEffect(() => {
    if (brand) {
      reset({
        name: brand.name,
        country: brand.country || '',
        notes: brand.notes || '',
      });
    } else {
      reset({ name: '', country: '', notes: '' });
    }
  }, [brand, reset]);

  const onSubmit = async (data: Brand) => {
    try {
      if (brand && brand.id) {
        await updateBrand(brand.id, data);
        toast.success('Brand updated successfully!');
      } else {
        await createBrand(data);
        toast.success('Brand created successfully!');
      }

      reset(); // clear form
      onSuccess?.(); // trigger table refresh
    } catch (err) {
      console.error(err);
      toast.error('Failed to save brand.');
    }
  };

  return (
    <form onSubmit={handleSubmit(onSubmit)} className="space-y-2">
      <input
        {...register('name', { required: true })}
        placeholder="Brand Name"
        className="border p-2 rounded w-full"
      />










































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































     

      <button
        type="submit"
        className="bg-blue-600 text-white px-4 py-2 rounded hover:bg-blue-700"
      >
        {brand ? 'Update Brand' : 'Add Brand'}
      </button>
    </form>
  );
};

export default BrandsForm;
